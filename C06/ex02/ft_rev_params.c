#include <unistd.h>

int	main(int argc, char **argv)
{
	int	i;
	int	c;

	c = 0;
	i = argc - 1;
	while (i > 0)
	{
		while (argv[i][c])
		{
			write(1, &argv[i][c], 1);
			c++;
		}
		c = 0;
		i--;
		write(1, "\n", 1);
	}
	return (0);
}
